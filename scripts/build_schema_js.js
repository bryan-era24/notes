/*
 * Purpose: Development script: copy db/schema.sql into backend/schema_sql.js so the app can show it offline on its setup screen.
 * Responsibilities: Write the file; tests/schema.test.js checks that both stay identical. Run: node scripts/build_schema_js.js
 */
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const ROOT = path.resolve(__dirname, "..");
const sql = fs.readFileSync(path.join(ROOT, "db", "schema.sql"), "utf8");
const out =
  '/*\n * Purpose: The database setup SQL (a copy of db/schema.sql) available offline, for the setup screen\'s "Copiar instrucciones".\n' +
  " * Responsibilities: Hold the text only. Generated by scripts/build_schema_js.js; tests/schema.test.js checks it matches db/schema.sql.\n */\n" +
  "window.NT = window.NT || {};\nNT.schemaSql = " +
  JSON.stringify(sql) +
  ";\n";
fs.writeFileSync(path.join(ROOT, "backend", "schema_sql.js"), out);
console.log("backend/schema_sql.js written");
